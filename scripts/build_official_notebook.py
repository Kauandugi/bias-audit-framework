def markdown(text: str):
    source = text.strip()
    return nbformat.v4.new_markdown_cell(source, id=cell_id("markdown", source))


def code(text: str):
    source = text.strip()
    return nbformat.v4.new_code_cell(source, id=cell_id("code", source))


def cell_id(cell_type: str, source: str) -> str:
    """Return a stable Jupyter cell ID for reproducible notebook builds."""

    payload = f"{cell_type}\0{source}".encode("utf-8")
    return hashlib.sha256(payload).hexdigest()[:12]


